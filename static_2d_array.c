#include <stdio.h>
#include <stdlib.h>

#define MATRIX_HEIGHT 4
#define MATRIX_WIDTH 5

void static_array_print(int A[][MATRIX_WIDTH], size_t N)
{
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < MATRIX_WIDTH; j++) {
            printf("%*d", 5, A[i][j]);
        }
        printf("\n");
    }
}

void static_array_test(size_t N)
{
    /* 
      1. ЧТО ТУТ ПРОИСХОДИТ?
      Мы просим операционку выделить ОДИН большой кусок памяти на куче (heap).
      Его размер складывается из двух частей:
      - N * sizeof(int *) -> «Шапка» из указателей (адреса наших будущих строк).
      - N * MATRIX_WIDTH * sizeof(int) -> Сами данные матрицы (все числа).
      Вся эта конструкция записывается в указатель A (указатель на указатель).
    */
    int **A = (int **)malloc(N * sizeof(int *) + N * MATRIX_WIDTH * sizeof(int));
    
    /* 
      2. ЧТО ЗНАЧИТ ЭТА СТРОКА: int *start = (int *)((char *)A + N * sizeof(int *));
      
      Нам нужно найти точное место, где заканчивается «шапка» из указателей и начинаются сами числа.
      - (char *)A  -> Принудительно говорим компьютеру: «Смотри на адрес A как на массив байтов (char весит ровно 1 байт)». Это нужно, чтобы шагать по памяти ровно по 1 байту, а не по кускам int.
      - N * sizeof(int *) -> Это размер нашей шапки (количество строк умножить на размер одного указателя).
      - (char *)A + [размер шапки] -> Смещаемся вправо по байтам ровно на длину шапки. Мы встали прямо на порог, где начинается блок с числами!
      - (int *)  -> Приводим этот адрес обратно к типу "указатель на int", чтобы дальше работать с нормальными числами.
      Результат записывается в переменную start — это чистый адрес начала нашей матрицы.
    */
    int *start = (int *)((char *)A + N * sizeof(int *));

    /* 
      3. НАСТРОЙКА УКАЗАТЕЛЕЙ (РАЗДАЧА КЛЮЧЕЙ)
      В массиве A у нас зарезервированы ячейки под строки (A[0], A[1], A[2]...).
      Здесь мы в цикле прописываем каждой строке её точный адрес в общем блоке данных:
      - start -> адрес начала первой строки.
      - start + MATRIX_WIDTH -> смещаемся на ширину строки и получаем адрес второй строки, и т.д.
      Благодаря этому дальше можно писать привычное A[i][j].
    */
    for (int i = 0; i < N; i++) {
        A[i] = start + i * MATRIX_WIDTH;
    }

    int x = 1;
    
    /* 
      4. ЗАПОЛНЕНИЕ: A[i][j] = x;
      Здесь мы обращаемся к матрице как к обычной таблице через квадратные скобки.
      Компьютер берет адрес строки A[i], прибавляет к нему смещение по столбцу j 
      и записывает туда текущее значение переменной x.
    */
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < MATRIX_WIDTH; j++) {
            A[i][j] = x;
            x += 1;
        }
    }
    
    static_array_print(A, N);

    /* memory investigation */
    printf("\n Direct memory access:\n");
    
    /* 
      5. ПРЯМОЙ ДОСТУП К ПАМЯТИ
      Так как мы выделили память ОДНИМ сплошным куском, числа лежат в ряд без разрывов.
      Указатель p встает на start и просто линейно шагает по всем 20 элементам подряд (*p),
      выводя их на экран.
    */
    for(int *p = start; p < start + (N * MATRIX_WIDTH); p++) {
        printf("%*3d", 5, *p);
    }
    printf("\n\n");

    /* 
      6. УДАЛЕНИЕ ПАМЯТИ
      Так как весь этот огромный блок (и шапка, и данные) был выделен одним вызовом malloc,
      мы освобождаем его тоже одной командой free(A). Никаких циклов не нужно!
    */
    free(A);
}

int main()
{
    static_array_test(MATRIX_HEIGHT);
    return 0;
}